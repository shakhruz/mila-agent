#!/bin/bash
# Публичное ядро не обещает «пробный резерв / подарок / $5 от нас» ни на одном языке (живая проба 04.11: «старт на пробном резерве от нас»).
H="$(cd "$(dirname "$0")" && pwd)"
hits=$(grep -rnE '\$5 |\$5$|\$5 на старт|first hundred|trial reserve|free \$5|пробн(ый|ом) запас|от нас|bepul|sinov zaxira|免费|礼物|前一百' "$H"/*.md 2>/dev/null)
if [ -z "$hits" ]; then echo '✅ ни «$5 от нас», ни «пробного запаса» в навыке знакомства'; echo "итог 1/1"; else echo "❌ обещание резерва:"; echo "$hits"; echo "итог 0/1"; exit 1; fi
